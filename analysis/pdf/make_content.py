def table(name):
    """CSV с ключ в първата колона -> {ключ: [стойности]}."""
    return {r[0]: r[1:] for r in read(name)[1:]}


def eur(x, d=2):
    """Български формат: интервал за хилядите, запетая за десетичните, € отпред."""
    x = float(x)
    s = f"{abs(x):,.{d}f}".replace(",", " ").replace(".", ",")
    return ("−" if x < 0 else "") + "€" + s


def n(x, d=0):
    s = f"{float(x):,.{d}f}".replace(",", " ").replace(".", ",")
    return s.replace("-", "−")


def pct(x, d=1):
    return n(float(x) * 100, d) + "%"


